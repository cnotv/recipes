const dictionaries: Record<string, Record<VoteTextKey, string>> = { en: english, de: german, jp: japanese, th: thai }

/** The vote screens' text in the language the rest of the site is showing; `{n}` and `{time}` are filled in. */
export const useVoteText = () => (key: VoteTextKey, values: Record<string, string | number> = {}): string =>
  Object.entries(values).reduce(
    (text, [name, value]) => text.replace(`{${name}}`, String(value)),
    (dictionaries[String(i18n.global.locale.value)] ?? english)[key],
  )

/** A recipe title in the site's language, falling back to English and then to whatever exists. */
export const pickTitle = (titles: Record<string, string>): string =>
  titles[String(i18n.global.locale.value)] ?? titles.en ?? Object.values(titles)[0] ?? ''
